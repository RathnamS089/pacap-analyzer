"""Tests for the optional local-model explainer (Ollama).

Branch goal (codex/ollama-explainer): optional plain-language notes on the
measured evidence, generated by the user's own local Ollama model. The
feature is strictly optional — the evidence review is complete without it —
and nothing ever leaves the machine: the model runs locally and receives
only the already-extracted facts and limitations, never raw packets.

No real Ollama install is required: the happy path runs against an
in-process fake Ollama HTTP server, and the unavailable path points at a
closed local port.
"""

import json
import threading
from http.server import BaseHTTPRequestHandler, HTTPServer
from pathlib import Path
from typing import Any, Dict, Iterator, List

import pytest
from scapy.layers.dot11 import Dot11, Dot11Beacon, Dot11Elt, RadioTap
from scapy.utils import wrpcap

from tracelens.analyzer import analyze_capture
from tracelens.explainer import (
    ExplainerUnavailable,
    ExplanationResult,
    build_prompt,
    explain_analysis,
)
from tracelens.reader import load_capture

AP_MAC = "aa:bb:cc:dd:ee:02"


def _sample_analysis(tmp_path: Path) -> Dict[str, Any]:
    """A real analyzer result for a one-beacon capture (no mocks)."""
    capture = tmp_path / "site.pcap"
    beacon = (
        RadioTap(
            present="TSFT+Flags+Rate+Channel+dBm_AntSignal+Antenna",
            ChannelFrequency=2412,
            dBm_AntSignal=-52,
        )
        / Dot11(
            type=0,
            subtype=8,
            addr1="ff:ff:ff:ff:ff:ff",
            addr2=AP_MAC,
            addr3=AP_MAC,
        )
        / Dot11Beacon(cap="ESS")
        / Dot11Elt(ID=0, info=b"SiteNet")  # SSID
        / Dot11Elt(ID=3, info=bytes([1]))  # DS parameter set (channel)
    )
    wrpcap(str(capture), [beacon])
    return analyze_capture(load_capture(capture))


class FakeOllama:
    """In-process stand-in for Ollama's HTTP API; records every request."""

    def __init__(
        self,
        response_text: str = "Signal looks steady on channel 1.",
        model: str = "fake-model",
        error_payload: Any = None,
    ) -> None:
        self.captured: List[Dict[str, Any]] = []
        self.response_text = response_text
        self.model = model
        self.error_payload = error_payload
        outer = self

        class Handler(BaseHTTPRequestHandler):
            def do_POST(self) -> None:
                length = int(self.headers.get("Content-Length", 0))
                outer.captured.append(json.loads(self.rfile.read(length)))
                if outer.error_payload is not None:
                    body = json.dumps({"error": outer.error_payload}).encode()
                    self.send_response(404)
                else:
                    body = json.dumps(
                        {
                            "model": outer.model,
                            "response": outer.response_text,
                            "done": True,
                        }
                    ).encode()
                    self.send_response(200)
                self.send_header("Content-Type", "application/json")
                self.send_header("Content-Length", str(len(body)))
                self.end_headers()
                self.wfile.write(body)

            def log_message(self, format: str, *args: Any) -> None:
                pass  # keep pytest output clean

        self.server = HTTPServer(("127.0.0.1", 0), Handler)
        self.url = "http://127.0.0.1:%d" % self.server.server_address[1]
        self._thread = threading.Thread(
            target=self.server.serve_forever, daemon=True
        )
        self._thread.start()

    def stop(self) -> None:
        self.server.shutdown()
        self.server.server_close()
        self._thread.join(timeout=5)


@pytest.fixture()
def fake_ollama() -> Iterator[FakeOllama]:
    server = FakeOllama()
    yield server
    server.stop()


def test_build_prompt_carries_facts_limitations_and_safety_rules(
    tmp_path: Path,
) -> None:
    prompt = build_prompt(_sample_analysis(tmp_path))

    # Measured facts are included.
    assert "SiteNet" in prompt
    # Limitations are preserved verbatim in meaning.
    assert "Roaming: cannot be assessed" in prompt
    # Safety rules the product lives by.
    assert "is NOT proof an event did not happen" in prompt
    assert "root cause" in prompt
    assert "ONLY" in prompt


def test_explain_analysis_uses_local_ollama_and_returns_text(
    tmp_path: Path, fake_ollama: FakeOllama
) -> None:
    analysis = _sample_analysis(tmp_path)

    result = explain_analysis(
        analysis, model="fake-model", url=fake_ollama.url, timeout=10.0
    )

    assert isinstance(result, ExplanationResult)
    assert result.text == fake_ollama.response_text
    assert result.model == "fake-model"

    # The model saw the extracted evidence, not the packets: the prompt IS
    # the request body, and it carries the facts and limitations.
    request = fake_ollama.captured[-1]
    assert request["model"] == "fake-model"
    assert request["stream"] is False
    assert "SiteNet" in request["prompt"]
    assert "Roaming: cannot be assessed" in request["prompt"]


def test_explain_analysis_raises_friendly_error_when_ollama_unreachable(
    tmp_path: Path,
) -> None:
    analysis = _sample_analysis(tmp_path)

    with pytest.raises(ExplainerUnavailable) as excinfo:
        explain_analysis(analysis, url="http://127.0.0.1:1", timeout=2.0)

    message = str(excinfo.value)
    assert "not reachable" in message
    assert "http://127.0.0.1:1" in message


def test_explain_analysis_surfaces_ollama_error_payload(tmp_path: Path) -> None:
    server = FakeOllama(error_payload="model 'nope' not found")
    try:
        analysis = _sample_analysis(tmp_path)
        with pytest.raises(ExplainerUnavailable) as excinfo:
            explain_analysis(analysis, model="nope", url=server.url, timeout=10.0)
        assert "not found" in str(excinfo.value)
    finally:
        server.stop()
